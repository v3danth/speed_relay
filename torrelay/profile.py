"""Named profiles: one target + one dedicated, pinnable Tor instance.

Layout under ``$XDG_CONFIG_HOME/torrelay/<name>/`` (default ~/.config)::

    profile.json   target + ports + pinned guards (source of truth)
    torrc          generated; %includes pinned.conf
    pinned.conf    generated; EntryNodes line (reloaded via SIGHUP)
    results.json   last benchmark, ranked
    data/          Tor DataDirectory
    tor.pid tor.log
"""

from __future__ import annotations

import json
import os
import re
import time
from dataclasses import asdict, dataclass, fields
from pathlib import Path
from typing import Iterable, Optional, Sequence

from torrelay.target import Target

_NAME_RE = re.compile(r"^[A-Za-z0-9_-]{1,40}$")
DEFAULT_SOCKS_PORT = 9060


@dataclass(frozen=True)
class Profile:
    name: str
    host: str
    scheme: str = "ssh"
    port: int = 22
    path: str = "/"
    user: Optional[str] = None
    key: Optional[str] = None
    insecure: bool = False
    socks_port: int = DEFAULT_SOCKS_PORT
    ctrl_port: int = DEFAULT_SOCKS_PORT + 1
    fallback_ports: tuple[int, ...] = (9050,)
    ssh_options: tuple[str, ...] = ()
    pinned: tuple[str, ...] = ()        # guard fingerprints
    pinned_exits: tuple[str, ...] = ()  # exit fingerprints (clearnet)

    @property
    def target(self) -> Target:
        return Target(self.scheme, self.host, self.port, self.path,
                      self.user, self.key, self.ssh_options, self.insecure)


def from_target(name: str, target: Target, **ports) -> Profile:
    return Profile(name=name, host=target.host, scheme=target.scheme,
                   port=target.port, path=target.path, user=target.user,
                   key=target.key, insecure=target.insecure,
                   ssh_options=target.ssh_options, **ports)


# --------------------------------------------------------------------------
# Paths
# --------------------------------------------------------------------------

def config_root() -> Path:
    base = os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config"
    return Path(base) / "torrelay"


def profile_dir(name: str) -> Path:
    if not _NAME_RE.match(name):
        raise ValueError(f"invalid profile name {name!r} "
                         "(letters, digits, _ and - only)")
    return config_root() / name


def paths(profile: Profile) -> dict[str, Path]:
    root = profile_dir(profile.name)
    return {
        "root": root,
        "json": root / "profile.json",
        "torrc": root / "torrc",
        "pinned": root / "pinned.conf",
        "results": root / "results.json",
        "data": root / "data",
        "pid": root / "tor.pid",
        "log": root / "tor.log",
    }


# --------------------------------------------------------------------------
# Pure rendering
# --------------------------------------------------------------------------

def render_torrc(profile: Profile) -> str:
    p = paths(profile)
    return "\n".join((
        f"# Generated by torrelay for profile '{profile.name}'. "
        "Edit profile.json instead.",
        f"SocksPort 127.0.0.1:{profile.socks_port} ExtendedErrors",
        f"ControlPort 127.0.0.1:{profile.ctrl_port}",
        "CookieAuthentication 1",
        f"DataDirectory {p['data']}",
        f"PidFile {p['pid']}",
        f"Log notice file {p['log']}",
        f"%include {p['pinned']}",
        "",
    ))


def render_pinned(guards: Sequence[str], exits: Sequence[str] = ()) -> str:
    def line(option: str, fps: Sequence[str]) -> str:
        return f"{option} " + ",".join(f"${fp}" for fp in fps) + "\n"

    body = "".join((line("EntryNodes", guards) if guards else "",
                    line("ExitNodes", exits) if exits else ""))
    return body or "# Nothing pinned; Tor chooses its own relays.\n"


def next_ports(existing: Iterable[Profile]) -> tuple[int, int]:
    """First (socks, ctrl) pair above all ports used by other profiles."""
    used = [p for prof in existing for p in (prof.socks_port, prof.ctrl_port)]
    socks = max([DEFAULT_SOCKS_PORT - 2, *used]) + 1
    socks += socks % 2 != DEFAULT_SOCKS_PORT % 2  # keep pairs aligned
    return socks, socks + 1


# --------------------------------------------------------------------------
# I/O
# --------------------------------------------------------------------------

def _from_dict(data: dict) -> Profile:
    known = {f.name for f in fields(Profile)}
    clean = {k: v for k, v in data.items() if k in known}
    tuples = {k: tuple(clean[k]) for k in
              ("fallback_ports", "ssh_options", "pinned", "pinned_exits")
              if k in clean}
    return Profile(**{**clean, **tuples})


def load(name: str) -> Profile:
    path = profile_dir(name) / "profile.json"
    if not path.exists():
        raise FileNotFoundError(f"no profile '{name}' (run: torrelay init)")
    return _from_dict(json.loads(path.read_text(encoding="utf-8")))


def list_all() -> list[Profile]:
    root = config_root()
    names = sorted(d.name for d in root.iterdir()
                   if (d / "profile.json").exists()) if root.exists() else []
    return list(map(load, names))


def save(profile: Profile) -> Profile:
    p = paths(profile)
    p["root"].mkdir(mode=0o700, parents=True, exist_ok=True)
    p["json"].write_text(json.dumps(asdict(profile), indent=2) + "\n",
                         encoding="utf-8")
    return profile


def write_tor_files(profile: Profile) -> None:
    p = paths(profile)
    p["data"].mkdir(mode=0o700, parents=True, exist_ok=True)
    p["torrc"].write_text(render_torrc(profile), encoding="utf-8")
    p["pinned"].write_text(render_pinned(profile.pinned,
                                         profile.pinned_exits),
                           encoding="utf-8")


def save_results(profile: Profile, payload: dict) -> Path:
    path = paths(profile)["results"]
    path.write_text(json.dumps({"timestamp": time.time(), **payload},
                               indent=2) + "\n", encoding="utf-8")
    return path


def load_results(profile: Profile) -> dict:
    path = paths(profile)["results"]
    if not path.exists():
        raise FileNotFoundError(
            f"no results for '{profile.name}' (run: torrelay bench "
            f"{profile.name})")
    return json.loads(path.read_text(encoding="utf-8"))
